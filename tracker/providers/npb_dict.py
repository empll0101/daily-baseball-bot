def _translate_npb_scores(text: str) -> str:
    """轉換速報字串中的比分與隊名簡稱，例：'ヤ 0-7 西' -> '養樂多 0-7 西武'"""
    abbrs = "|".join(re.escape(k) for k in NPB_TEAM_ABBR_MAP.keys())
    pattern = rf"(?<![a-zA-Z\u3040-\u30ff\u4e00-\u9fa5])({abbrs})\s*(\d+\s*-\s*\d+)\s*({abbrs})(?![a-zA-Z\u3040-\u30ff\u4e00-\u9fa5])"

    def repl(m: re.Match) -> str:
        t1 = NPB_TEAM_ABBR_MAP.get(m.group(1), m.group(1))
        score = re.sub(r"\s*", "", m.group(2))
        t2 = NPB_TEAM_ABBR_MAP.get(m.group(3), m.group(3))
        return f"{t1} {score} {t2}"

    return re.sub(pattern, repl, text)


def translate_npb_text(raw_text: str) -> str:
    """完整翻譯 NPB Yahoo! 即時賽況速報字串"""
    # 1. 處理比分隊名縮寫（例：ヤ 0-7 西 -> 養樂多 0-7 西武、神 8-3 楽 -> 阪神 8-3 樂天）
    text = _translate_npb_scores(raw_text)

    # 2. 處理局勢、球數與球隊動作正則
    text = re.sub(r"(\d+)球目の", r"第\1球，", text)
    text = re.sub(r"の(\d+-\d+)から", r"，球數 \1，", text)
    text = re.sub(r"の(\d+-\d+)", r"，球數 \1", text)
    text = re.sub(r"中(\d+)日で", r"休\1天後", text)
    text = re.sub(r"で(\w+)先制", r"，\1先馳得點", text)
    text = re.sub(r"で(\w+)勝ち越し", r"，\1超前比分", text)
    text = re.sub(r"で(\w+)同点", r"，\1追平比分", text)
    text = re.sub(r"(\d+-\d+-\d+)のダブルプレー", r"\1 雙殺打", text)

    # 3. 循序替換各類棒球術語
    for jp_text, tw_text in REPLACE_MAP:
        text = text.replace(jp_text, tw_text)

    # 4. 整理標點符號與多餘空白
    text = re.sub(r"，\s*，", "，", text)
    text = text.strip()

    # 5. 若仍有日文假名，自動記錄至 log 檔案供後續快速擴充字典
    if re.search(r"[\u3040-\u30ff]", text):
        try:
            import os
            os.makedirs("data", exist_ok=True)
            with open("data/untranslated_terms.log", "a", encoding="utf-8") as f:
                f.write(f"RAW: {raw_text}\nAFTER: {text}\n---\n")
        except Exception:
            pass

    return text
